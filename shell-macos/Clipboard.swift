// Watches the clipboard and hands new text to the core.
// macOS has no clipboard-change notification, so (like every clipboard
// manager) we compare NSPasteboard.changeCount twice a second: one integer
// read, no work unless it changed.

import AppKit

final class ClipboardWatcher {
    private var last = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Markers password managers and other apps set on things that must not
    /// be kept (http://nspasteboard.org).
    private static let skip: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    func start() {
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        t.tolerance = 0.25
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    private func check() {
        let pb = NSPasteboard.general
        guard pb.changeCount != last else { return }
        last = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skip), let text = pb.string(forType: .string) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName ?? ""
        DispatchQueue.global(qos: .utility).async { Core.clipboardAdd(text, app: app) }
    }
}
